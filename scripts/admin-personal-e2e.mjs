let csrf
async function req(path, method = 'GET', data, expected = 200, owner = context, token = csrf) {
  const response = await owner.request.fetch(config.studio + path, { method,
    headers: token ? { [token.headerName]: token.token } : {}, ...(data === undefined ? {} : { data }) })
  assert.equal(response.status(), expected, `${method} ${path}`)
  return expected === 204 ? undefined : response.json()
}
async function login(owner, username = config.username, password = config.password) {
  const token = await req('/api/v1/auth/csrf', 'GET', undefined, 200, owner, null)
  await req('/api/v1/auth/login', 'POST', { username, password }, 200, owner, token)
  return req('/api/v1/auth/csrf', 'GET', undefined, 200, owner, null)
}
